  /// 타입별 게임 가져오기
  static List<GameRound> getGamesByType(GameType type) {
    switch (type) {
      case GameType.daily:
        return dailyGames;
      case GameType.select:
        return selectGames;
      case GameType.vibe:
        return vibeGames;
      case GameType.prime:
        return primeGames;
    }
  }

  /// 모든 게임 가져오기
  static List<GameRound> getAllGames() {
    return [...dailyGames, ...selectGames, ...vibeGames, ...primeGames];
  }

  /// ID로 게임 찾기
  static GameRound? getGameById(String id) {
    try {
      return getAllGames().firstWhere((game) => game.id == id);
    } catch (e) {
      return null;
    }
  }
